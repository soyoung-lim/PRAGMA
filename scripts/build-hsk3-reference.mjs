import fs from "node:fs/promises";
import path from "node:path";
import {
  HSK3_SOURCE_ID,
  HSK3_TOPIC_DERIVATION_VERSION,
  HSK3_TOPIC_MAPPING_VERSION,
  boolValue,
  chunks,
  pgSmallintArray,
  pgTextArrayFromPipe,
  readCsv,
  sqlBool,
  sqlText,
  writeCsv,
} from "./lib/hsk3-reference-data.mjs";

const root = process.cwd();
const vocabPath = path.join(root, "data/hsk3/source/hsk3_vocab_extracted.csv");
const topicsPath = path.join(root, "data/hsk3/source/hsk3_topics_extracted.csv");
const derivedDir = path.join(root, "data/hsk3/derived");
const seedDir = path.join(root, "supabase/seed");

const vocab = await readCsv(vocabPath);
const topics = await readCsv(topicsPath);
if (vocab.length !== 11000) throw new Error(`Expected 11000 vocabulary rows, got ${vocab.length}`);
if (topics.length !== 427) throw new Error(`Expected 427 topic rows, got ${topics.length}`);

await fs.mkdir(derivedDir, { recursive: true });
await fs.mkdir(seedDir, { recursive: true });

const topicRaw = topics.map((row, index) => ({
  topic_seq: index + 1,
  level_band: row.level_band,
  level_int: row.level_int,
  l1: row.l1,
  l2: row.l2,
  l3: row.l3,
}));
const topicDerivations = topics.map((row, index) => ({
  topic_seq: index + 1,
  derivation_version: HSK3_TOPIC_DERIVATION_VERSION,
  l3_terms: row.l3_terms,
  n_terms: row.n_terms,
  has_explicit_open_marker: row.open_ended,
  path: row.path,
  appears_in_levels: row.appears_in_levels,
  n_levels: row.n_levels,
}));
const topicMappings = topics.map((row, index) => ({
  topic_seq: index + 1,
  mapping_version: HSK3_TOPIC_MAPPING_VERSION,
  axis_code: row.axis,
  scope_code: row.scope,
  app_domain_code: row.app_domain,
  has_state_administration_frame: row.state_framed,
  coding_status: "legacy_imported_unverified",
  selection_status: "unreviewed",
  exclusion_reason_code: "",
  coded_by: "",
  coded_at: "",
  notes: "",
}));

function appearsInLevelsSqlArray(value) {
  const normalized = String(value)
    .split("|")
    .map((level) => (level === "7-9" ? "7" : level))
    .join(",");
  return pgSmallintArray(`{${normalized}}`);
}

await writeCsv(
  path.join(derivedDir, "hsk3_topics_raw.csv"),
  ["topic_seq", "level_band", "level_int", "l1", "l2", "l3"],
  topicRaw,
);
await writeCsv(
  path.join(derivedDir, "hsk3_topic_derivations.csv"),
  [
    "topic_seq",
    "derivation_version",
    "l3_terms",
    "n_terms",
    "has_explicit_open_marker",
    "path",
    "appears_in_levels",
    "n_levels",
  ],
  topicDerivations,
);
await writeCsv(
  path.join(derivedDir, "pragma_hsk_topic_mappings.csv"),
  [
    "topic_seq",
    "mapping_version",
    "axis_code",
    "scope_code",
    "app_domain_code",
    "has_state_administration_frame",
    "coding_status",
    "selection_status",
    "exclusion_reason_code",
    "coded_by",
    "coded_at",
    "notes",
  ],
  topicMappings,
);

function insertStatement(table, columns, valueRows, conflictSql) {
  return [
    `INSERT INTO ${table} (${columns.join(",")})`,
    "VALUES",
    valueRows.join(",\n"),
    conflictSql,
    "",
  ].join("\n");
}

const seed = [];
seed.push("-- Generated by scripts/build-hsk3-reference.mjs. Do not hand-edit.");
seed.push("-- Schema migration must be applied first. Seed application requires separate approval.");
seed.push("BEGIN;", "");
seed.push(
  insertStatement(
    "public.hsk_reference_sources",
    [
      "id",
      "title",
      "publisher",
      "released_at",
      "effective_at",
      "official_url",
      "sha256",
      "manifest_version",
      "extraction_version",
      "notes",
    ],
    [
      `(${sqlText(HSK3_SOURCE_ID)},${sqlText("新版HSK考试大纲")},${sqlText("中外语言交流合作中心")},${sqlText("2025-11")},${sqlText("2026-07")},${sqlText("https://hsk.cn-bj.ufileos.com/3.0/%E6%96%B0%E7%89%88HSK%E8%80%83%E8%AF%95%E5%A4%A7%E7%BA%B21219.pdf")},${sqlText("EC74CE0439E837BBB15154BE13E747AE798903B2FD3A331629DF6C3B45504941")},${sqlText("hsk3_reference_manifest_v1")},${sqlText("legacy_extraction_audited_v1")},${sqlText("Original executable PDF extraction script unavailable; full PDF-to-CSV audit passed 2026-08-09.")})`,
    ],
    "ON CONFLICT (id) DO UPDATE SET title=EXCLUDED.title, publisher=EXCLUDED.publisher, released_at=EXCLUDED.released_at, effective_at=EXCLUDED.effective_at, official_url=EXCLUDED.official_url, sha256=EXCLUDED.sha256, manifest_version=EXCLUDED.manifest_version, extraction_version=EXCLUDED.extraction_version, notes=EXCLUDED.notes;",
  ),
);

for (const batch of chunks(vocab, 1000)) {
  const rows = batch.map(
    (row) =>
      `(${sqlText(HSK3_SOURCE_ID)},${Number(row.seq)},${sqlText(row.headword)},${sqlText(row.pinyin)},${Number(row.sense_no)},${sqlText(row.source_form)},${sqlText(row.pinyin_norm)},${sqlText(row.pos)},${Number(row.intro_level)},${sqlText(row.intro_band)},${pgSmallintArray(row.extra_levels)},${sqlBool(boolValue(row.is_multi_sense, "is_multi_sense"))},${sqlBool(boolValue(row.is_polyphone, "is_polyphone"))},${sqlBool(boolValue(row.is_phrase, "is_phrase"))},${sqlText(row.source_note)})`,
  );
  seed.push(
    insertStatement(
      "public.hsk3_vocab",
      [
        "source_id",
        "seq",
        "headword",
        "pinyin",
        "sense_no",
        "source_form",
        "pinyin_norm",
        "pos",
        "intro_level",
        "intro_band",
        "extra_levels",
        "is_multi_sense",
        "is_polyphone",
        "is_phrase",
        "source_note",
      ],
      rows,
      "ON CONFLICT (source_id,seq) DO UPDATE SET headword=EXCLUDED.headword, pinyin=EXCLUDED.pinyin, sense_no=EXCLUDED.sense_no, source_form=EXCLUDED.source_form, pinyin_norm=EXCLUDED.pinyin_norm, pos=EXCLUDED.pos, intro_level=EXCLUDED.intro_level, intro_band=EXCLUDED.intro_band, extra_levels=EXCLUDED.extra_levels, is_multi_sense=EXCLUDED.is_multi_sense, is_polyphone=EXCLUDED.is_polyphone, is_phrase=EXCLUDED.is_phrase, source_note=EXCLUDED.source_note;",
    ),
  );
}

seed.push(
  insertStatement(
    "public.hsk3_topics",
    ["source_id", "topic_seq", "level_band", "level_int", "l1", "l2", "l3"],
    topicRaw.map(
      (row) =>
        `(${sqlText(HSK3_SOURCE_ID)},${row.topic_seq},${sqlText(row.level_band)},${Number(row.level_int)},${sqlText(row.l1)},${sqlText(row.l2)},${sqlText(row.l3)})`,
    ),
    "ON CONFLICT (source_id,topic_seq) DO UPDATE SET level_band=EXCLUDED.level_band, level_int=EXCLUDED.level_int, l1=EXCLUDED.l1, l2=EXCLUDED.l2, l3=EXCLUDED.l3;",
  ),
);
seed.push(
  insertStatement(
    "public.hsk3_topic_derivations",
    [
      "source_id",
      "topic_seq",
      "derivation_version",
      "l3_terms",
      "n_terms",
      "has_explicit_open_marker",
      "path",
      "appears_in_levels",
      "n_levels",
    ],
    topicDerivations.map(
      (row) =>
        `(${sqlText(HSK3_SOURCE_ID)},${row.topic_seq},${sqlText(row.derivation_version)},${pgTextArrayFromPipe(row.l3_terms)},${Number(row.n_terms)},${sqlBool(boolValue(row.has_explicit_open_marker, "has_explicit_open_marker"))},${sqlText(row.path)},${appearsInLevelsSqlArray(row.appears_in_levels)},${Number(row.n_levels)})`,
    ),
    "ON CONFLICT (source_id,topic_seq,derivation_version) DO UPDATE SET l3_terms=EXCLUDED.l3_terms, n_terms=EXCLUDED.n_terms, has_explicit_open_marker=EXCLUDED.has_explicit_open_marker, path=EXCLUDED.path, appears_in_levels=EXCLUDED.appears_in_levels, n_levels=EXCLUDED.n_levels;",
  ),
);
seed.push(
  insertStatement(
    "public.pragma_hsk_topic_mappings",
    [
      "source_id",
      "topic_seq",
      "mapping_version",
      "axis_code",
      "scope_code",
      "app_domain_code",
      "has_state_administration_frame",
      "coding_status",
      "selection_status",
      "exclusion_reason_code",
      "coded_by",
      "coded_at",
      "notes",
    ],
    topicMappings.map(
      (row) =>
        `(${sqlText(HSK3_SOURCE_ID)},${row.topic_seq},${sqlText(row.mapping_version)},${sqlText(row.axis_code)},${sqlText(row.scope_code)},${sqlText(row.app_domain_code)},${sqlBool(boolValue(row.has_state_administration_frame, "has_state_administration_frame"))},${sqlText(row.coding_status)},${sqlText(row.selection_status)},NULL,NULL,NULL,NULL)`,
    ),
    "ON CONFLICT (source_id,topic_seq,mapping_version) DO UPDATE SET axis_code=EXCLUDED.axis_code, scope_code=EXCLUDED.scope_code, app_domain_code=EXCLUDED.app_domain_code, has_state_administration_frame=EXCLUDED.has_state_administration_frame, coding_status=EXCLUDED.coding_status, selection_status=EXCLUDED.selection_status, exclusion_reason_code=EXCLUDED.exclusion_reason_code, coded_by=EXCLUDED.coded_by, coded_at=EXCLUDED.coded_at, notes=EXCLUDED.notes;",
  ),
);

seed.push(`DO $$
DECLARE
  vocab_count integer;
  topic_count integer;
  derivation_count integer;
  mapping_count integer;
BEGIN
  SELECT count(*) INTO vocab_count FROM public.hsk3_vocab WHERE source_id = '${HSK3_SOURCE_ID}';
  SELECT count(*) INTO topic_count FROM public.hsk3_topics WHERE source_id = '${HSK3_SOURCE_ID}';
  SELECT count(*) INTO derivation_count FROM public.hsk3_topic_derivations WHERE source_id = '${HSK3_SOURCE_ID}';
  SELECT count(*) INTO mapping_count FROM public.pragma_hsk_topic_mappings WHERE source_id = '${HSK3_SOURCE_ID}';
  IF vocab_count <> 11000 THEN
    RAISE EXCEPTION 'HSK 3.0 vocab count %; expected 11000', vocab_count;
  END IF;
  IF topic_count <> 427 THEN
    RAISE EXCEPTION 'HSK 3.0 topic count %; expected 427', topic_count;
  END IF;
  IF derivation_count <> 427 THEN
    RAISE EXCEPTION 'HSK 3.0 topic derivation count %; expected 427', derivation_count;
  END IF;
  IF mapping_count <> 427 THEN
    RAISE EXCEPTION 'HSK 3.0 researcher mapping count %; expected 427', mapping_count;
  END IF;
  IF EXISTS (
    SELECT 1
    FROM (VALUES (1,300),(2,200),(3,500),(4,1000),(5,1600),(6,1800),(7,5600)) expected(level,count)
    LEFT JOIN (
      SELECT intro_level AS level, count(*)::integer AS count
      FROM public.hsk3_vocab
      WHERE source_id = '${HSK3_SOURCE_ID}'
      GROUP BY intro_level
    ) actual USING (level)
    WHERE actual.count IS DISTINCT FROM expected.count
  ) THEN
    RAISE EXCEPTION 'HSK 3.0 vocab level distribution mismatch';
  END IF;
END $$;

COMMIT;
`);

await fs.writeFile(
  path.join(seedDir, "hsk3_reference_seed.sql"),
  `${seed.join("\n")}\n`,
  "utf8",
);

console.log(`Built ${topicRaw.length} topic rows and ${vocab.length} vocabulary seed rows.`);
